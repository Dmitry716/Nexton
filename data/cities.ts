export type CountryCode = "BY" | "RU" | "LV" | "LT";
export type CurrencyCode = "BYN" | "RUB" | "EUR";

export interface City {
  slug: string;
  name: string;
  namePrepositional: string; // в ком? в чём? (в Минске, в Орше)
  nameGenitive: string; // кого? чего? (Минска, Орши)
  region: string;
  country: CountryCode;
  currency: CurrencyCode;
  description: string;
  keywords: string[];
}

export function currencyForCountry(country: CountryCode): CurrencyCode {
  if (country === "RU") return "RUB";
  if (country === "LV" || country === "LT") return "EUR";
  return "BYN";
}

